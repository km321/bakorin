import type { EntityAST, FieldAST, SchemaAST } from "./ast.ts";

function tsType(field: FieldAST): string {
  switch (field.type) {
    case "text":
    case "email":
    case "password":
    case "date":
    case "datetime":
    case "file":
    case "richtext":
      return "string";
    case "json":
      return "JsonValue";
    case "number":
      return "number";
    case "integer":
      return "number";
    case "boolean":
      return "boolean";
    case "enum":
      return (field.enumValues ?? []).map((value) => JSON.stringify(value)).join(" | ") || "string";
    case "relation":
      return field.relation?.many ? "string[]" : "string";
    default: {
      const _never: never = field.type;
      return _never;
    }
  }
}

function pascal(name: string): string {
  return name.replace(/(^[a-z])|([-_][a-z])/g, (chunk) => chunk.replace(/[-_]/, "").toUpperCase());
}

function fieldLine(field: FieldAST): string {
  if (field.secret) {
    return `  // ${field.name} is write-only and never returned`;
  }
  // Many to many fields always come back as a list (empty when nothing is linked).
  const optional = field.required || field.relation?.many ? "" : "?";
  return `  ${field.name}${optional}: ${tsType(field)};`;
}

function entityInterface(entity: EntityAST): string {
  const lines = entity.fields.filter((field) => !field.secret).map(fieldLine);
  const writes = entity.fields
    .filter((field) => field.name !== "id" && field.name !== "createdAt" && field.name !== "updatedAt")
    .map((field) => {
      const optional = field.required && field.defaultValue === undefined ? "" : "?";
      return `  ${field.name}${optional}: ${tsType(field)};`;
    });
  const name = pascal(entity.name);
  return `export interface ${name} {
${lines.join("\n")}
}

export interface ${name}Write {
${writes.join("\n")}
}
`;
}

export function generateTypes(ast: SchemaAST): string {
  const interfaces = ast.entities.map(entityInterface).join("\n");
  const mapLines = ast.entities.map((entity) => `  ${entity.name}: ${pascal(entity.name)};`).join("\n");
  const writeMap = ast.entities.map((entity) => `  ${entity.name}: ${pascal(entity.name)}Write;`).join("\n");
  const usesJson = ast.entities.some((entity) => entity.fields.some((field) => field.type === "json" && !field.secret));
  const jsonAlias = usesJson
    ? `/** Any JSON value. Narrow it with a type guard or a cast to your own type. */
export type JsonValue = string | number | boolean | null | JsonValue[] | { [key: string]: JsonValue };

`
    : "";
  return `/* Generated by bakorin. Do not edit. */

${jsonAlias}${interfaces}
export interface BakorinEntities {
${mapLines}
}

export interface BakorinWrites {
${writeMap}
}

export type BakorinEntityName = keyof BakorinEntities;
${schemaConst(ast)}`;
}

const SYSTEM_FIELDS = new Set(["id", "createdAt", "updatedAt"]);

/** Fields the server fills from the signed in user, like ownerId. Mirrors ownedByFields on the server. */
function ownerFieldNames(entity: EntityAST, authEntity: string): Set<string> {
  const names = new Set<string>();
  for (const rules of Object.values(entity.policies)) {
    for (const rule of rules) {
      if (rule.kind === "owner" && rule.field !== "id") {
        names.add(rule.field);
      }
    }
  }
  for (const field of entity.fields) {
    if (field.relation?.to === authEntity && !entity.auth) {
      names.add(field.name);
    }
  }
  return names;
}

/**
 * A runtime description of the schema for UI helpers (RecordForm, DataTable in
 * @bakorin/sdk). Field names, types, and rules only: no data and no secrets.
 */
function schemaConst(ast: SchemaAST): string {
  const entities: Record<string, unknown> = {};
  for (const entity of ast.entities) {
    const owners = ownerFieldNames(entity, ast.auth.entity);
    entities[entity.name] = {
      name: entity.name,
      display: entity.display,
      fields: entity.fields.map((field) => {
        const out: Record<string, unknown> = { name: field.name, type: field.type };
        if (field.required) out.required = true;
        if (field.enumValues) out.enumValues = field.enumValues;
        if (field.relation) out.relation = field.relation.many ? { to: field.relation.to, many: true } : { to: field.relation.to };
        if (field.writable !== "any") out.writable = field.writable;
        if (field.secret) out.secret = true;
        if (field.private) out.private = true;
        if (owners.has(field.name)) out.owner = true;
        if (SYSTEM_FIELDS.has(field.name)) out.system = true;
        if (field.description) out.description = field.description;
        if (field.defaultValue !== undefined && !field.secret) out.defaultValue = field.defaultValue;
        return out;
      }),
    };
  }
  const value = {
    entities,
    auth: { entity: ast.auth.entity, identityField: ast.auth.identityField, passwordField: ast.auth.passwordField },
  };
  return `
/** Field names, types, and rules for UI helpers like RecordForm in @bakorin/sdk. */
export const bakorinSchema = ${JSON.stringify(value, null, 2)} as const;
`;
}
