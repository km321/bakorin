#!/usr/bin/env node
import { cp, mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { createInterface } from "node:readline/promises";
import { stdin as input, stdout as output } from "node:process";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

type Frontend = "astro" | "next" | "none";
type Schema = "blank" | "auth" | "todo";

interface Options {
  name: string;
  directory: string;
  frontend: Frontend;
  schema: Schema;
  yes: boolean;
}

const ROOT = dirname(fileURLToPath(import.meta.url));
const TEMPLATES = join(ROOT, "..", "templates");

function arg(flag: string): string | undefined {
  const index = process.argv.indexOf(flag);
  if (index >= 0) {
    return process.argv[index + 1];
  }
  return undefined;
}

function hasFlag(flag: string): boolean {
  return process.argv.includes(flag);
}

function parseFrontend(value: string | undefined): Frontend | undefined {
  if (value === "astro" || value === "next" || value === "none") {
    return value;
  }
  return undefined;
}

function parseSchema(value: string | undefined): Schema | undefined {
  if (value === "blank" || value === "auth" || value === "auth-only") {
    return value === "auth-only" ? "auth" : value === "auth" ? "auth" : "blank";
  }
  if (value === "todo" || value === "leads" || value === "todo/leads") {
    return "todo";
  }
  return undefined;
}

function slug(value: string): string {
  return value
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "") || "bakorin-app";
}

async function prompt(question: string, fallback: string): Promise<string> {
  const rl = createInterface({ input, output });
  const answer = await rl.question(`${question} (${fallback}): `);
  rl.close();
  return answer.trim() || fallback;
}

async function copyDir(from: string, to: string): Promise<void> {
  await mkdir(to, { recursive: true });
  const entries = await readdir(from, { withFileTypes: true });
  for (const entry of entries) {
    const src = join(from, entry.name);
    const dest = join(to, entry.name);
    if (entry.isDirectory()) {
      if (entry.name === "node_modules" || entry.name === "dist" || entry.name === ".astro" || entry.name === ".next") {
        continue;
      }
      await copyDir(src, dest);
    } else if (entry.name === "package.json") {
      const text = (await readFile(src, "utf8")).replace(/"@bakorin\/sdk": "[^"]+"/g, '"@bakorin/sdk": "^0.1.0"');
      await writeFile(dest, text);
    } else {
      await cp(src, dest);
    }
  }
}

async function writeTemplated(src: string, dest: string, name: string): Promise<void> {
  const text = (await readFile(src, "utf8")).replaceAll("{{APP_NAME}}", name);
  await writeFile(dest, text);
}

async function resolveFrontendTemplate(kind: "astro" | "next"): Promise<string> {
  const packaged = join(TEMPLATES, kind);
  try {
    await readdir(packaged);
    return packaged;
  } catch {
    return resolve(ROOT, "../../../examples", `${kind}-starter`);
  }
}

function schemaFile(schema: Schema): string {
  switch (schema) {
    case "blank":
      return "blank.yaml";
    case "auth":
      return "auth.yaml";
    case "todo":
      return "todo.yaml";
    default: {
      const _never: never = schema;
      return _never;
    }
  }
}

async function run(options: Options): Promise<void> {
  const dest = resolve(options.directory);
  await mkdir(dest, { recursive: true });
  const appName = slug(options.name);
  await writeTemplated(join(TEMPLATES, "schemas", schemaFile(options.schema)), join(dest, "app.yaml"), appName);
  await cp(join(TEMPLATES, "hooks.ts"), join(dest, "hooks.ts"));
  await cp(join(TEMPLATES, "env.example"), join(dest, ".env.example"));
  await cp(join(TEMPLATES, "gitignore"), join(dest, ".gitignore"));
  await cp(join(TEMPLATES, "Dockerfile"), join(dest, "Dockerfile"));
  await cp(join(TEMPLATES, "railway.json"), join(dest, "railway.json"));
  await cp(join(TEMPLATES, "railway.toml"), join(dest, "railway.toml"));
  await cp(join(TEMPLATES, "docker-compose.yml"), join(dest, "docker-compose.yml"));
  await writeFile(
    join(dest, "README.md"),
    `# ${appName}

Bakorin backend generated by create-bakorin.

## Run locally (about five minutes)

1. Copy \`.env.example\` to \`.env\` and set \`JWT_SECRET\`.
2. Start the API:

   \`\`\`bash
   bunx bakorin dev
   # or, from a Bakorin checkout: bun packages/server/src/cli.ts dev --dir .
   \`\`\`

3. Open http://127.0.0.1:4371/admin/ after signing up, then promote that user to admin.
${
  options.frontend === "none"
    ? ""
    : `
4. In another terminal, start the ${options.frontend} app in \`web/\`:

   \`\`\`bash
   cd web
   npm install
   npm run dev
   \`\`\`

   \`BAKORIN_URL\` defaults to http://127.0.0.1:4371.
`
}

See docs/quickstart.md in the Bakorin repo for the full walkthrough.
`,
  );

  if (options.frontend !== "none") {
    const from = await resolveFrontendTemplate(options.frontend);
    await copyDir(from, join(dest, "web"));
  }

  console.log(`Created ${dest}`);
  console.log(`Schema: ${options.schema}   Frontend: ${options.frontend}`);
  console.log("Next: copy .env.example to .env, then bunx bakorin dev");
}

async function main(): Promise<void> {
  const positional = process.argv.slice(2).find((item) => !item.startsWith("-"));
  const yes = hasFlag("--yes") || hasFlag("-y") || !process.stdin.isTTY;
  let name = arg("--name") ?? positional ?? "";
  let frontend = parseFrontend(arg("--frontend") ?? arg("--fw"));
  let schema = parseSchema(arg("--schema") ?? arg("--starter"));
  if (!yes) {
    if (!name) {
      name = await prompt("Project name", "my-app");
    }
    if (!frontend) {
      const raw = await prompt("Frontend (astro | next | none)", "astro");
      frontend = parseFrontend(raw) ?? "astro";
    }
    if (!schema) {
      const raw = await prompt("Starter schema (blank | auth-only | todo)", "todo");
      schema = parseSchema(raw) ?? "todo";
    }
  }
  name = name || "my-app";
  frontend = frontend ?? "astro";
  schema = schema ?? "todo";
  const directory = arg("--dir") ?? name;
  await run({ name, directory, frontend, schema, yes });
}

main().catch((error: unknown) => {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
});
